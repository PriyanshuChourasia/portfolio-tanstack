import { createBank, type Difficulty, type OptionKey, type QuestionInput } from './types'

/**
 * Analogy Master Practice — a 100-question, level-by-level analogy paper.
 *
 * A : B :: C : D reads "A is related to B in the same way that C is related to D".
 * The paper climbs from simple word relations to multi-step and very difficult
 * patterns, so it is served in bank order (see `sequential` on the exam definition).
 *
 * Every question is newly written to follow the analogy patterns seen in SSC
 * CHSL / CGL / MTS / GD, RRB and SBI / IBPS PO papers — none is an actual paper
 * question, and each is labelled `pyq_pattern`. Every explanation starts with the
 * relationship used so the review screen doubles as a pattern guide.
 */

const LEVELS = {
  1: { subtopic: 'Level 1 · Word / vocabulary analogy', pattern: 'SSC MTS / GD word analogy' },
  2: { subtopic: 'Level 2 · Conceptual / GK analogy', pattern: 'SSC CHSL / RRB conceptual analogy' },
  3: { subtopic: 'Level 3 · Number analogy (basic)', pattern: 'SSC CHSL number analogy' },
  4: { subtopic: 'Level 4 · Number analogy (moderate)', pattern: 'SSC CGL number analogy' },
  5: { subtopic: 'Level 5 · Letter analogy', pattern: 'SSC CHSL / CGL letter analogy' },
  6: { subtopic: 'Level 6 · Word / letter transformation', pattern: 'SSC CGL / IBPS PO letter-transformation analogy' },
  7: { subtopic: 'Level 7 · Alpha-numeric analogy', pattern: 'SSC CGL / RRB alpha-numeric analogy' },
  8: { subtopic: 'Level 8 · Figural / non-verbal analogy', pattern: 'SSC CHSL / MTS non-verbal analogy' },
  9: { subtopic: 'Level 9 · Advanced multi-step analogy', pattern: 'SSC CGL Tier-1 advanced analogy' },
  10: { subtopic: 'Level 10 · Very difficult', pattern: 'SSC CGL / SBI PO high-difficulty analogy' },
} as const

type Level = keyof typeof LEVELS

function q(
  n: number,
  level: Level,
  difficulty: Difficulty,
  questionText: string,
  options: [string, string, string, string],
  correctOption: OptionKey,
  explanation: string,
): QuestionInput {
  return {
    id: `ana-${String(n).padStart(3, '0')}`,
    topic: 'Analogy',
    subtopic: LEVELS[level].subtopic,
    difficulty,
    questionText,
    options,
    correctOption,
    explanation,
    pattern: LEVELS[level].pattern,
  }
}

